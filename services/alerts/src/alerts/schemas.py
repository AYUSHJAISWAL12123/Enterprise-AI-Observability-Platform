"""Schemas for the alerting pipeline."""

from __future__ import annotations

from enum import StrEnum

from pydantic import BaseModel


class Severity(StrEnum):
    INFO = "info"
    WARNING = "warning"
    CRITICAL = "critical"


class MetricRow(BaseModel):
    """A row fetched from the evals table combined with basic event metadata."""

    event_id: str
    trace_id: str
    application_name: str
    groundedness_score: int
    relevance_score: int
    safety_flag: bool
    embedding_distance: float
    judge_rationale: str
    evaluated_at: str


class Alert(BaseModel):
    """An alert generated by the rules engine."""

    alert_id: str  # Typically f"{event_id}-{rule_name}"
    event_id: str
    trace_id: str
    application_name: str
    rule_name: str
    severity: Severity
    message: str
    created_at: str  # ISO-8601
